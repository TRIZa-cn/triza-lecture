def rewrite(p, parts):
    """parts=[(text,bold)]；清空原有 run，按 parts 重建，12pt。"""
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    for text, bold in parts:
        r = p.add_run(text)
        r.font.size = Pt(12)
        r.bold = bold

def find(prefix, start=0):
    for i in range(start, len(d.paragraphs)):
        if d.paragraphs[i].text.strip().startswith(prefix):
            return d.paragraphs[i]
    raise KeyError(prefix)

def ins_before(anchor, parts):
    p = anchor.insert_paragraph_before("", style="Normal")
    for text, bold in parts:
        r = p.add_run(text)
        r.font.size = Pt(12)
        r.bold = bold
    return p

