def kpage(prs, kk, tt, notes=""):
    s = B.page(prs, kk, tt, notes=notes)
    for sh in s.shapes:
        if sh.has_text_frame and sh.text_frame.text.strip() == kk.strip():
            for p in sh.text_frame.paragraphs:
                for r in p.runs: r.font.size = Pt(KICK)
    return s

def kfoot(s, idx):
    tf = B.textbox(s, B.ML, 6.98, B.CW - 1.3, 0.32)
    B.rich(tf.paragraphs[0], FOOT, 12, B.INK3, accent=B.RED, spc=100)
    tf2 = B.textbox(s, B.SW - B.MR - 0.7, 6.98, 0.7, 0.32)
    B.para(tf2, "%02d" % idx, 12, B.INK3, align=PP_ALIGN.RIGHT, first=True)

def card(s, l, t, w, h, label, body, accent=B.RED):
    r = B.rect(s, l, t, w, h, B.Z1, line_col=B.LINE)
    r.text_frame.word_wrap = True
    r.text_frame.margin_left = Inches(0.18); r.text_frame.margin_right = Inches(0.14)
    r.text_frame.margin_top = Inches(0.14)
    tf = r.text_frame
    B.para(tf, label, 20, accent, bold=True, first=True, space_after=8)
    for i, line in enumerate(body):
        B.para(tf, line, MIN, B.INK, space_after=7)
    return r

